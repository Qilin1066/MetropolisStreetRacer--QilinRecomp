#!/bin/sh
# Compiles the FSR 1 compute shaders (host/src/fsr/fsr.comp, over AMD's
# FSR 1 headers) to SPIR-V, into host/src/fsr/fsr_spirv.inc, which
# is committed: the runtime builds no shaders. Needs glslangValidator and
# spirv-val (the Vulkan SDK, or a distribution's glslang-tools and
# spirv-tools). Run from the repository's root after changing either.
set -eu
# The upstream files, as CMake fetches them (configure first): build/third_party.
inc=${QILIN_THIRD_PARTY:-build/third_party}
src=host/src/fsr/fsr.comp
out=host/src/fsr/fsr_spirv.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/fsr_spirv.sh from fsr.comp and AMD FidelityFX FSR 1's headers (MIT, THIRD_PARTY.md); don't edit."
    for pass in EASU RCAS; do
        glslangValidator -V -I"$inc/fsr1" -I"$inc/smaa" --target-env vulkan1.3 -D"$pass" -S comp -o "$tmp/$pass.spv" "$src" >/dev/null
        spirv-val --target-env vulkan1.3 "$tmp/$pass.spv"
        lower=$(echo "$pass" | tr 'A-Z' 'a-z')
        echo "inline constexpr uint32_t kFsr_${lower}[] = {"
        od -An -v -tx4 "$tmp/$pass.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
        echo "};"
    done
} > "$out"
echo "wrote $out"
