#!/usr/bin/env python3
"""Write msr/src/romfont_glyphs.inc: the glyphs msr serves in place of the
Dreamcast boot ROM's font, taken from GNU Unifont's Japanese variant.

The boot ROM's font is Sega's and can't be shipped. The game reads it
through Sega's font library (in MSR.BIN, 0x8C1406B4), which fixes the
layout this file follows (docs/runtime.md, "The boot ROM's font"):

  narrow glyphs, 12x24, 36 bytes each, from offset 0: index = c - 32 for
      c = 32..127, 96 + c - 160 for c = 160..255 (ISO 8859-1); 288 slots;
  wide glyphs, 24x24, 72 bytes each, from offset 0x2880: JIS X 0208 rows
      1-7 (index = (row - 1) * 94 + cell - 1), then rows 16-84 (index =
      658 + (row - 16) * 94 + cell - 1); 7,056 slots, ending at 0x7E900,
      where the library's tables of icons start.

Unifont's glyphs are 8x16 and 16x16; msr scales them to 12x24 and 24x24
when the game first asks for the font (msr/src/romfont.cpp). This file
keeps them as Unifont has them, in hex, one per slot ("" for a slot with no
character). JIS X 0208 is mapped to Unicode with Python's own EUC-JP codec.

Unifont is GPL-2.0-or-later with the GNU font embedding exception, and
OFL-1.1 (https://unifoundry.com/unifont/). The generated file is a
derivative and carries the same terms.

Usage (developer tool; the generated file is committed):
  curl -O https://unifoundry.com/pub/unifont/unifont-18.0.01/font-builds/unifont_jp-18.0.01.hex.gz
  python3 tools/make_romfont.py unifont_jp-18.0.01.hex.gz
"""
import gzip
import hashlib
import pathlib
import sys

VERSION = "18.0.01"
SHA256 = "c9c3af339e1f86076c95e4d3c34806a0cf6f0d37a4e168d697a04c1ea948736b"  # unifont_jp-18.0.01.hex.gz
OUT = pathlib.Path(__file__).resolve().parent.parent / "msr" / "src" / "romfont_glyphs.inc"

NARROW_SLOTS = 288
WIDE_ROWS = list(range(1, 8)) + list(range(16, 85))
WIDE_SLOTS = 7056  # rows 1-7 and 16-83 in full, and row 84's first six (all it has)


def narrow_char(index):
    if index < 96:
        return 32 + index
    if index < 192:
        return 160 + index - 96
    return None


def wide_char(index):
    """The Unicode character of a wide slot, or None."""
    if index < 7 * 94:
        row, cell = index // 94 + 1, index % 94 + 1
    else:
        row, cell = 16 + (index - 658) // 94, (index - 658) % 94 + 1
    try:
        text = bytes([row + 0xA0, cell + 0xA0]).decode("euc_jp")
    except UnicodeDecodeError:
        return None
    return ord(text) if len(text) == 1 else None


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: make_romfont.py unifont_jp-%s.hex.gz" % VERSION)
    raw = pathlib.Path(sys.argv[1]).read_bytes()
    got = hashlib.sha256(raw).hexdigest()
    if got != SHA256:
        sys.exit("%s: SHA-256 %s, expected %s (unifont_jp-%s.hex.gz)" % (sys.argv[1], got, SHA256, VERSION))
    glyphs = {}
    for line in gzip.decompress(raw).decode("ascii").splitlines():
        code, bits = line.split(":")
        glyphs[int(code, 16)] = bits

    def glyph(c, width):
        # No glyph for DEL, the C1 controls, or the soft hyphen (invisible; Unifont draws it as a
        # 16-wide box of its code).
        if c is None or c in (0x7F, 0xAD) or (0x80 <= c < 0xA0):
            return ""
        bits = glyphs.get(c)
        if bits is None:
            sys.exit("U+%04X has no glyph in Unifont" % c)
        if width == 16 and len(bits) == 32:
            # JIS X 0208's Latin-1 symbols (´ ¨ ° ± × ÷ § ¶), half-width in Unifont: centred.
            bits = "".join("%04X" % (int(bits[i:i + 2], 16) << 4) for i in range(0, 32, 2))
        if len(bits) != width * 4:
            sys.exit("U+%04X is %d wide in Unifont, not %d" % (c, len(bits) // 4, width))
        return bits

    narrow = [glyph(narrow_char(i), 8) for i in range(NARROW_SLOTS)]
    wide = []
    missing = 0
    for i in range(WIDE_SLOTS):
        c = wide_char(i)
        if c is None:
            missing += 1
        wide.append(glyph(c, 16))
    lines = [
        "// Generated by tools/make_romfont.py from GNU Unifont %s (unifont_jp-%s.hex.gz," % (VERSION, VERSION),
        "// SHA-256 %s). Do not edit." % SHA256,
        "// Unifont: GPL-2.0-or-later with the GNU font embedding exception, and OFL-1.1",
        "// (https://unifoundry.com/unifont/). These glyphs are a derivative under the same terms.",
        "// %d narrow slots (8x16, hex), %d wide slots (16x16, hex), in the boot ROM font's order;" % (NARROW_SLOTS, WIDE_SLOTS),
        "// \"\" is a slot with no character (%d wide)." % missing,
        "inline constexpr const char* kNarrowGlyphs[%d] = {" % NARROW_SLOTS,
    ]
    lines += ['    "%s",' % g for g in narrow]
    lines += ["};", "inline constexpr const char* kWideGlyphs[%d] = {" % WIDE_SLOTS]
    lines += ['    "%s",' % g for g in wide]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print("wrote %s: %d narrow, %d wide (%d without a character)" % (OUT, sum(1 for g in narrow if g), WIDE_SLOTS - missing, missing))


if __name__ == "__main__":
    main()
