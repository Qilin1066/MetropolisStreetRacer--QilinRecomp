#!/bin/sh
# Compiles the SMAA shaders (host/src/smaa/smaa.glsl, over SMAA.hlsl) to SPIR-V, into host/src/smaa/smaa_spirv.inc,
# which is committed: the runtime builds no shaders. Needs glslangValidator
# and spirv-val. Run from the repository's root after changing either.
set -eu
# The upstream files, as CMake fetches them (configure first): build/third_party.
inc=${QILIN_THIRD_PARTY:-build/third_party}
src=host/src/smaa/smaa.glsl
out=host/src/smaa/smaa_spirv.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/smaa_spirv.sh from smaa.glsl and SMAA (MIT, THIRD_PARTY.md); don't edit."
    for pass in 1 2 3; do
        for stage in vert frag; do
            if [ "$stage" = vert ]; then kind=-DVERTEX; else kind=-DFRAGMENT; fi
            glslangValidator -V -I"$inc/fsr1" -I"$inc/smaa" --target-env vulkan1.3 -DPASS=$pass $kind -S "$stage" -o "$tmp/s.spv" "$src" >/dev/null
            spirv-val --target-env vulkan1.3 "$tmp/s.spv"
            echo "inline constexpr uint32_t kSmaa${pass}_${stage}[] = {"
            od -An -v -tx4 "$tmp/s.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
            echo "};"
        done
    done
} > "$out"
echo "wrote $out"
